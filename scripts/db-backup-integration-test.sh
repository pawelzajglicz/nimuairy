#!/usr/bin/env bash
# Runs scripts/backup-db.sh and scripts/verify-db-backup.sh against a throwaway container of the
# PostgreSQL image production uses (read from compose.yaml), so neither the local postgres-nimuairy
# container nor the VPS is touched. Needs Docker and `docker login dhi.io`. Takes about a minute.
# scripts/db-backup-test.sh covers the failure paths that need injected faults. Run from the
# repository root:
#   bash scripts/db-backup-integration-test.sh
set -euo pipefail
# Git Bash on Windows would turn container paths such as /dev/null into Windows paths.
export MSYS_NO_PATHCONV=1

SCRIPTS=$(cd "${0%/*}" && pwd)
readonly BACKUP=$SCRIPTS/backup-db.sh VERIFY=$SCRIPTS/verify-db-backup.sh
IMAGE=$(grep -m 1 -oE 'dhi\.io/postgres:[^[:space:]]+' "$SCRIPTS/../compose.yaml")
readonly IMAGE C=nimuairy-backup-it-$$

work=$(mktemp -d)
cleanup() {
  docker rm -f "$C" >/dev/null 2>&1
  rm -rf "$work"
  return 0
}
trap cleanup EXIT

passed=0 failed=0 shown=false
run() {
  rc=0
  out=$(env POSTGRES_CONTAINER="$C" "$@" 2>&1) || rc=$?
  shown=false
}
check() {
  local what=$1
  shift
  if "$@"; then
    passed=$((passed + 1))
    return
  fi
  failed=$((failed + 1))
  echo "  FAIL: $what" >&2
  if ! $shown; then
    shown=true
    echo "  Output (exit $rc):" >&2
    while IFS= read -r line; do echo "    | $line" >&2; done <<<"$out"
  fi
}
has() { grep -qF -- "$1" <<<"$out"; }
exit_is() { [[ $rc == "$1" ]]; }
same() { [[ $1 == "$2" ]]; }
differ() { [[ -n $1 && -n $2 && $1 != "$2" ]]; }
matches() { [[ $1 =~ $2 ]]; }
section() { echo "== $*"; }
db_of() { sed -n 's/^Database:   \([^ ]*\) (temporary)$/\1/p' <<<"$1"; }

sql() { docker exec -i "$C" psql -X -w -U app -v ON_ERROR_STOP=1 -At "$@"; }
# What the scripts must never change: the list of databases and the "production" data.
snapshot() {
  sql -d postgres -c 'SELECT datname FROM pg_database ORDER BY 1'
  sql -d nimuairy -c "SELECT md5(string_agg(u::text, ';' ORDER BY id)) FROM users u" \
    -c 'SELECT count(*) FROM characters' -c 'SELECT count(*) FROM databasechangelog'
}
unchanged() { [[ $(snapshot) == "$before" ]]; }
# The tables of changelogs 001 and 002 and a reduced Liquibase history: the smoke test only reads
# these table names and counts rows.
schema() {
  local tables=$1
  echo "CREATE TABLE databasechangelog (id varchar(255) NOT NULL, author varchar(255) NOT NULL,
          filename varchar(255) NOT NULL);
        INSERT INTO databasechangelog VALUES
          ('001-create-users-table', 'nimuairy', 'db/changelog/001-create-users-table.xml'),
          ('002-create-characters-table', 'nimuairy', 'db/changelog/002-create-characters-table.xml');
        CREATE TABLE users (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          username varchar(255) NOT NULL UNIQUE, password varchar(255) NOT NULL);
        INSERT INTO users (username, password) VALUES ('alice', 'hash-a'), ('bob', 'hash-b');"
  [[ $tables == all ]] && echo "CREATE TABLE characters (id bigint GENERATED BY DEFAULT AS IDENTITY
          PRIMARY KEY, name varchar(255) NOT NULL, description text,
          created_at timestamp with time zone NOT NULL);"
  return 0
}

echo "Starting $IMAGE as $C..."
docker run -d --name "$C" -e POSTGRES_USER=app -e POSTGRES_PASSWORD=test -e POSTGRES_DB=nimuairy \
  "$IMAGE" >/dev/null
# Over TCP: during initialisation the entrypoint's temporary server listens only on the socket.
for _ in {1..60}; do
  docker exec "$C" pg_isready -q -h 127.0.0.1 -U app -d nimuairy && break
  sleep 1
done
docker exec "$C" pg_isready -q -h 127.0.0.1 -U app -d nimuairy || { echo "ERROR: $C did not start" >&2; exit 1; }
schema all | sql -d nimuairy >/dev/null
sql -d postgres -c 'CREATE DATABASE incomplete' >/dev/null
schema users-only | sql -d incomplete >/dev/null
before=$(snapshot)

section "backup-db.sh with the real pg_dump and pg_restore"
backups=$work/backups
run env BACKUP_DIR="$backups" bash "$BACKUP" integration-test
dump=$(ls -A "$backups")
check "exits 0" exit_is 0
check "writes one dump and no .tmp" matches "$dump" '^nimuairy-[0-9]{8}T[0-9]{6}Z-integration-test\.dump$'
check "the dump is a custom-format archive" same "$(head -c 5 "$backups/$dump")" PGDMP
check "changes nothing in the database" unchanged

section "verify-db-backup.sh restores that dump"
run env BACKUP_DIR="$backups" bash "$VERIFY"
db=$(db_of "$out")
check "exits 0" exit_is 0
check "names the dump" has "Verifying $backups/$dump"
check "runs on PostgreSQL 18" has "Container:  $C (PostgreSQL 18."
check "counts the restored rows" has "Smoke test: OK (2 changesets, 2 users, 0 characters)"
check "drops the temporary database" has "Cleanup:    dropped $db"
check "passes" has "RESULT: PASSED"
check "leaves the databases and their data as they were" unchanged

section "verify-db-backup.sh rejects a truncated dump"
truncated=$work/truncated
mkdir "$truncated"
# The last bytes belong to the last table's data, so the table of contents is still whole.
head -c -32 "$backups/$dump" >"$truncated/$dump"
run env BACKUP_DIR="$truncated" bash "$VERIFY"
check "exits non-zero" test "$rc" -ne 0
check "fails at the restore" has "RESULT: FAILED at restore"
check "drops the temporary database" has "Cleanup:    dropped"
check "leaves the databases and their data as they were" unchanged

section "verify-db-backup.sh rejects a dump without the characters table"
incomplete=$work/incomplete
mkdir "$incomplete"
docker exec "$C" pg_dump -w -U app -d incomplete -Fc >"$incomplete/nimuairy-20260101T000000Z-incomplete.dump"
run env BACKUP_DIR="$incomplete" bash "$VERIFY"
check "exits non-zero" test "$rc" -ne 0
check "shows the SQL error" has 'relation "characters" does not exist'
check "fails at the smoke test" has "RESULT: FAILED at smoke"
check "drops the temporary database" has "Cleanup:    dropped"
check "leaves the databases and their data as they were" unchanged

section "two verify-db-backup.sh runs at once"
for i in 1 2; do
  (
    rc=0
    POSTGRES_CONTAINER=$C BACKUP_DIR=$backups bash "$VERIFY" >"$work/parallel$i.out" 2>&1 || rc=$?
    echo "$rc" >"$work/parallel$i.rc"
  ) &
done
wait
out=$(cat "$work"/parallel*.out) rc="$(<"$work/parallel1.rc") $(<"$work/parallel2.rc")" shown=false
db1=$(db_of "$(<"$work/parallel1.out")") db2=$(db_of "$(<"$work/parallel2.out")")
check "both pass" exit_is "0 0"
check "they use different databases" differ "$db1" "$db2"
check "leave the databases and their data as they were" unchanged

echo "$passed passed, $failed failed"
((failed == 0))
